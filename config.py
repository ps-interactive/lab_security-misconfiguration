"""Application configuration."""
import os
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
INSTANCE_DIR = BASE_DIR / "instance"
DATABASE_PATH = INSTANCE_DIR / "app.db"
JWT_SECRET_PATH = INSTANCE_DIR / "jwt_secret.key"

JWT_ALGORITHM = "HS256"
JWT_EXPIRY_MINUTES = 60
MIN_SECRET_LENGTH = 32


def get_jwt_secret() -> str:
    """Return the key used to sign and verify access tokens.

    The JWT_SECRET environment variable wins if set; otherwise the random key
    generated by `python seed.py` is read from the instance folder.
    """
    secret = os.environ.get("JWT_SECRET")
    if secret is None:
        try:
            secret = JWT_SECRET_PATH.read_text(encoding="utf-8").strip()
        except FileNotFoundError:
            raise RuntimeError("JWT secret not found. Run `python seed.py` first.") from None
    if len(secret) < MIN_SECRET_LENGTH:
        raise RuntimeError(f"JWT secret must be at least {MIN_SECRET_LENGTH} characters long.")
    return secret
